#!/usr/bin/env python3
"""Writes android/app/src/main/cpp/zone_coords.h: a time zone ID -> coordinates.

ANDROID FORK, Phase 8a (fork.h section 11). The sky follows the real sun and the
seasons follow the hemisphere, and both need to know roughly where the phone is.
The phone's time zone ID ("Europe/Madrid") already says that: the IANA database
records the coordinates of each zone's principal city in zone.tab. So the app
needs no location permission and sends nothing anywhere -- a zone is a city's
worth of accuracy, which is minutes on a sunrise, and plenty for a season.

Old and alternative names ("US/Eastern", "Asia/Calcutta", "Europe/Belfast") are
links in tzdata.zi and are resolved to their target's coordinates here, since
Android reports whichever name the system was set with.

    python3 tools/gen_zone_coords.py [zoneinfo dir]   # default /usr/share/zoneinfo

Re-run when the tz database gains a zone. The output is sorted by ID for a
binary search.
"""
import os
import re
import sys

OUT = os.path.join(os.path.dirname(__file__), '..', 'android', 'app', 'src', 'main', 'cpp',
                   'zone_coords.h')


def dms(s, deg_digits):
    """'+4230' or '+423012' (and the longitude's 3-digit degrees) -> degrees."""
    sign = -1 if s[0] == '-' else 1
    s = s[1:]
    d = int(s[:deg_digits])
    m = int(s[deg_digits:deg_digits + 2])
    sec = int(s[deg_digits + 2:deg_digits + 4]) if len(s) > deg_digits + 2 else 0
    return sign * (d + m / 60 + sec / 3600)


def main():
    zi = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/zoneinfo'
    coords = {}
    for line in open(os.path.join(zi, 'zone.tab'), encoding='utf-8'):
        if line.startswith('#') or not line.strip():
            continue
        cc, co, tz = line.split('\t')[:3]
        m = re.match(r'([+-]\d+)([+-]\d+)$', co)
        lat = dms(m.group(1), 2)
        lon = dms(m.group(2), 3)
        coords[tz.strip()] = (lat, lon)
    links = 0
    for line in open(os.path.join(zi, 'tzdata.zi'), encoding='utf-8'):
        if not line.startswith('L '):
            continue
        _, target, alias = line.split()
        # A link may point at another link; follow it to a zone with coordinates.
        seen = set()
        while target not in coords and target not in seen:
            seen.add(target)
            nxt = [l.split()[1] for l in open(os.path.join(zi, 'tzdata.zi'), encoding='utf-8')
                   if l.startswith('L ') and l.split()[2] == target]
            if not nxt:
                break
            target = nxt[0]
        if target in coords and alias not in coords:
            coords[alias] = coords[target]
            links += 1
    if len(coords) < 400:
        sys.exit(f'only {len(coords)} zones: is {zi} a full tz database?')
    rows = sorted(coords.items())
    with open(OUT, 'w', encoding='ascii') as f:
        f.write('// GENERATED by tools/gen_zone_coords.py from the IANA tz database\n')
        f.write('// (zone.tab, with tzdata.zi\'s links resolved). Do not edit by hand.\n')
        f.write('// A zone ID -> its principal city, in tenths of a degree, sorted by ID.\n')
        f.write('#pragma once\n#include <stdint.h>\n\n')
        f.write('struct ZoneCoord { const char *id; int16_t lat10, lon10; };\n')
        f.write(f'static const ZoneCoord ZONE_COORDS[{len(rows)}] = {{\n')
        for tz, (lat, lon) in rows:
            f.write(f'  {{ "{tz}", {round(lat * 10)}, {round(lon * 10)} }},\n')
        f.write('};\n')
    print(f'{OUT}: {len(rows)} zones ({links} links)')


if __name__ == '__main__':
    main()
